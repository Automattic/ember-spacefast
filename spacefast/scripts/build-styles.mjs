// Preserve original Ember/Lexxy CSS without unsupported native CSS imports.
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, '.spacefast/build/ember.css');
const input = resolve(root, 'client/ember/index.css');
const source = await readFile(input, 'utf8');
const tailwindImport = '@import "tailwindcss";';
if (!source.includes(tailwindImport)) throw new Error('Ember changed its Tailwind import; review the Spacefast stylesheet build.');
// Use the stylesheet's original directory for relative imports. Restrict scanning
// to app files so ignored or historical output cannot change the generated bundle.
const configured = source.replace(tailwindImport, [
  '@import "tailwindcss" source(none);',
  '@source "../";',
  '@source "./";',
  '@source "../../pages";',
  '@source not "../ember-styles.ts";',
].join('\n'));
await mkdir(dirname(output), {recursive:true});
execFileSync(resolve(root, 'node_modules/.bin/tailwindcss'), ['-i','-','-o',output,'--minify'], {
  cwd:dirname(input), input:configured, stdio:['pipe','inherit','inherit'],
});
const files = [output, 'node_modules/@37signals/lexxy/dist/stylesheets/lexxy-content.css', 'node_modules/@37signals/lexxy/dist/stylesheets/lexxy-editor.css', 'client/ember/components/workspace/rich-text-editor.css'];
let css = (await Promise.all(files.map(file=>readFile(resolve(root,file),'utf8')))).map(text=>text.replace(/^@import\s+[^;]+;\s*$/gm,'')).join('\n');
// The compiled stylesheet is injected into the page, so source-relative SVG masks
// need to travel with it instead of resolving against a room or thread URL.
const iconUrl = /url\("\.\.\/icons\/iconoir\/([a-z0-9-]+\.svg)"\)/g;
const iconNames = new Set([...css.matchAll(iconUrl)].map(match => match[1]));
const icons = new Map(await Promise.all([...iconNames].map(async name => [
  name,
  await readFile(resolve(root, 'client/ember/components/icons/iconoir', name), 'utf8'),
])));
css = css.replace(iconUrl, (_, name) => `url("data:image/svg+xml,${encodeURIComponent(icons.get(name))}")`);
// Native Zero also emits stock Tailwind utilities. Keep Ember's original custom
// breakpoint and token utilities above that layer rather than mixing two md values.
const marker='@layer utilities{';const layer=css.indexOf(marker);
if(layer>=0){let index=layer+marker.length,depth=1,quote=null,escaped=false;const start=index;
 while(depth&&index<css.length){const char=css[index++];if(escaped){escaped=false;continue;}if(char==='\\'){escaped=true;continue;}if(quote){if(char===quote)quote=null;}else if(char==='"'||char==="'")quote=char;else if(char==='{')depth++;else if(char==='}')depth--;}
 if(depth)throw new Error('Unbalanced Ember utility CSS');css=css.slice(0,layer)+css.slice(start,index-1)+css.slice(index);
}
await writeFile(resolve(root,'client/ember-styles.ts'), '/* Generated by node scripts/build-styles.mjs. */\nexport const emberStyles = '+JSON.stringify(css)+';\n');
