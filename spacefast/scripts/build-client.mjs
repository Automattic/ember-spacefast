// The native page mounts this opaque, minified browser asset. Data/auth/storage
// remain the native Zero SDK on the same origin; no external application server.
import {build} from 'esbuild';
import {mkdir,writeFile,readdir,unlink} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const result=await build({absWorkingDir:root,entryPoints:['client/browser-entry.tsx'],bundle:true,minify:true,write:false,format:'esm',platform:'browser',target:['es2023'],jsx:'automatic',define:{'process.env.NODE_ENV':'"production"'},legalComments:'eof'});
const code=result.outputFiles[0].contents;const hash=createHash('sha256').update(code).digest('hex').slice(0,16);const name=`ember-app.${hash}.js`;
await mkdir(resolve(root,'assets'),{recursive:true});
// Retain older content-addressed assets for already-open native pages.
await writeFile(resolve(root,'assets',name),code);
await writeFile(resolve(root,'client/asset-manifest.ts'),`// Generated by scripts/build-client.mjs\nexport const emberAssetUrl = "/assets/${name}";\n`);
console.log(`Native Ember browser asset: ${name} (${code.length} bytes)`);
